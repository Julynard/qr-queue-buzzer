// Writes the Better Auth tables as SQL for D1 migrations:
//   node scripts/auth-schema.ts > migrations/0001_auth.sql
// Builds the same options the Worker uses (src/auth.ts) against an empty in-memory SQLite database.
// Pass --infra to include the tables of the optional Better Auth Infrastructure plugins.
import { DatabaseSync } from "node:sqlite";
import { getMigrations } from "better-auth/db/migration";
import { authOptions } from "../src/auth.ts";

const env = {
  DB: new DatabaseSync(":memory:"),
  EMAIL_MODE: "console",
  BETTER_AUTH_SECRET: "schema-only-secret-schema-only-secret",
  TURNSTILE_SECRET_KEY: "x",
  BETTER_AUTH_API_KEY: process.argv.includes("--infra") ? "schema-only" : undefined,
} as unknown as Env;
const { compileMigrations } = await getMigrations(authOptions(env, "http://127.0.0.1:8787"));
console.log("-- Generated by scripts/auth-schema.ts from src/auth.ts (Better Auth tables). Do not edit by hand.");
console.log((await compileMigrations()).trim());
